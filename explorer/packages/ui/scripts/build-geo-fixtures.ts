type Point = [number, number];
type Area = { code: string; name: string };

/** Cells of a (cols x rows) grid over a bounding box, corners and edge midpoints jittered once so neighbours share them. */
function gridFeatures(box: [number, number, number, number], cols: number, rows: number, names: Area[], seed: number) {
  const [west, south, east, north] = box;
  let state = seed;
  const jitter = () => {
    state = (state * 1103515245 + 12345) % 2147483648;
    return state / 2147483648 - 0.5;
  };
  const dx = (east - west) / cols;
  const dy = (north - south) / rows;
  // Vertex lattice at half steps: (2c, 2r) are corners, odd indices are edge midpoints.
  const lattice = new Map<string, Point>();
  const vertex = (i: number, j: number): Point => {
    const key = `${i},${j}`;
    let point = lattice.get(key);
    if (!point) {
      const border = i === 0 || j === 0 || i === cols * 2 || j === rows * 2;
      const amount = border ? 0.12 : 0.3;
      point = [
        Number((west + (i * dx) / 2 + jitter() * dx * amount).toFixed(4)),
        Number((north - (j * dy) / 2 + jitter() * dy * amount).toFixed(4)),
      ];
      lattice.set(key, point);
    }
    return point;
  };
  const features = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const area = names[r * cols + c]!;
      const [i, j] = [c * 2, r * 2];
      // Clockwise with north up, the winding d3-geo expects for an exterior ring.
      const ring = [
        vertex(i, j), vertex(i + 1, j), vertex(i + 2, j), vertex(i + 2, j + 1),
        vertex(i + 2, j + 2), vertex(i + 1, j + 2), vertex(i, j + 2), vertex(i, j + 1), vertex(i, j),
      ];
      features.push({ type: "Feature" as const, properties: area, geometry: { type: "Polygon" as const, coordinates: [ring] } });
    }
  }
  return { type: "FeatureCollection" as const, features };
}

