function emit(file: string, exportName: string, doc: string, collection: ReturnType<typeof gridFeatures>, object: string) {
  const topo = topology({ [object]: collection });
  const body = `// GENERATED by scripts/build-geo-fixtures.ts. ${doc} Invented geometry, CC0; see that script.\nimport type { Topology } from "topojson-specification";\n\nexport const ${exportName} = ${JSON.stringify(topo)} as unknown as Topology;\n`;
  writeFileSync(join(import.meta.dirname, "..", "src/domain/samples/geo", file), body);
}

