"""The checked-in reference tables placement matches against, and the two reviewed files beside them.

One directory (`DEFAULT_DATA_DIR`, or `--placement-data` / `PIPELINE_PLACEMENT_DATA`) holds:

- `counties.csv`: `iso,siruta_jud,name`, the 42 counties (ISO 3166-2:RO without the `RO-`, SIRUTA's JUD code, Romanian name).
- `uats.csv`, `villages.csv`, `table-sources.json`: generated by `pipeline geo-table` from the archived SIRUTA, Wikidata and ANCPI
  snapshots (see geo/table.py). Absent until the operator generates them: placement then stops at the county.
- `locality_aliases.csv`: `county,anaf_name,siruta_name`, a reviewed typo fix per line (ships empty).
- `national_authorities.csv`: `cui,national,override,name,reason`, the reviewed classification (see scope.py).
"""
from __future__ import annotations

import csv
from pathlib import Path

from .matching import County, Gazetteer, Uat, Village, bare_uat_name, fold

DEFAULT_DATA_DIR = Path(__file__).parent / "data"
UAT_COLUMNS = ["siruta", "county_iso", "siruta_jud", "tip", "name", "name_folded", "lon", "lat", "point_source"]
VILLAGE_COLUMNS = ["siruta", "uat_siruta", "name", "name_folded", "postal_code"]


def read_csv(path: Path) -> list[dict[str, str]]:
    """Rows of a UTF-8 CSV, `#` comment lines skipped. A missing file is the caller's to check."""
    with path.open(encoding="utf-8", newline="") as f:
        lines = (line for line in f if line.strip() and not line.lstrip().startswith("#"))
        return list(csv.DictReader(lines))


def read_counties(data_dir: Path) -> list[County]:
    return [County(r["iso"], r["siruta_jud"], r["name"]) for r in read_csv(data_dir / "counties.csv")]


def read_uat_rows(data_dir: Path) -> list[dict[str, str]]:
    path = data_dir / "uats.csv"
    return read_csv(path) if path.is_file() else []


def read_aliases(data_dir: Path) -> dict[tuple[str, str], str]:
    path = data_dir / "locality_aliases.csv"
    if not path.is_file():
        return {}
    return {(r["county"].strip().upper(), fold(r["anaf_name"])): fold(r["siruta_name"]) for r in read_csv(path)}


def load_gazetteer(data_dir: Path | str | None = None) -> tuple[Gazetteer, bool]:
    """(the tables indexed for matching, whether a UAT table exists). Without `uats.csv` only the county is matchable."""
    base = Path(data_dir) if data_dir else DEFAULT_DATA_DIR
    uat_rows = read_uat_rows(base)
    uats = [Uat(r["siruta"], r["county_iso"], r["tip"], r["name"], r.get("name_folded") or bare_uat_name(r["name"])) for r in uat_rows]
    villages_path = base / "villages.csv"
    villages = [Village(r["siruta"], r["uat_siruta"], r["name"], r["name_folded"], r["postal_code"] or None)
                for r in (read_csv(villages_path) if villages_path.is_file() else [])]
    return Gazetteer(read_counties(base), uats, villages, read_aliases(base)), bool(uat_rows)
